// Renders tokens.css from the source. A name becomes `--lab-` plus its kebab-case path:
// palette neutral.900 is --lab-neutral-900, semantic statusOkTint is --lab-status-ok-tint.

import {
  borderWidth,
  breakpoints,
  focusRing,
  layer,
  motion,
  palette,
  radius,
  semanticColor,
  shadow,
  space,
  target,
  type,
  width,
  type PaletteRef,
  type ShadowLayer,
} from "./tokens.ts";

const PREFIX = "--lab-";

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

function px(value: number): string {
  return value === 0 ? "0" : `${value}px`;
}

function rem(valuePx: number): string {
  return `${valuePx / 16}rem`;
}

function paletteVar(ref: PaletteRef): string {
  return `var(${PREFIX}${ref.replace(".", "-")})`;
}

function shadowValue(layers: readonly ShadowLayer[]): string {
  return layers
    .map((l) => `${px(l.x)} ${px(l.y)} ${px(l.blur)} ${px(l.spread)} ${l.color}`)
    .join(", ");
}

type Section = { title: string; entries: [string, string][] };

function sections(): Section[] {
  return [
    {
      title: "Palette",
      entries: Object.entries(palette).flatMap(([family, steps]) =>
        Object.entries(steps).map(([step, value]): [string, string] => [
          `${family}-${step}`,
          value,
        ]),
      ),
    },
    {
      title: "Spacing, 4 px grid",
      entries: Object.entries(space).map(([step, value]) => [`space-${step}`, px(value)]),
    },
    {
      title: "Radii",
      entries: Object.entries(radius).map(([name, value]) => [
        `radius-${name}`,
        px(value),
      ]),
    },
    {
      title: "Type sizes and line heights",
      entries: Object.entries(type).flatMap(([name, t]): [string, string][] => [
        [`font-size-${name}`, rem(t.size)],
        [`line-height-${name}`, rem(t.lineHeight)],
      ]),
    },
    {
      title: "Line and surface widths",
      entries: [
        ["border-width", px(borderWidth)],
        ...Object.entries(width).map(([name, value]): [string, string] => [
          `width-${name}`,
          px(value),
        ]),
      ],
    },
    {
      title: "Shadows",
      entries: Object.entries(shadow).map(([name, layers]) => [
        `shadow-${name}`,
        shadowValue(layers),
      ]),
    },
    {
      title: "Stacking layers",
      entries: Object.entries(layer).map(([name, value]) => [
        `layer-${name}`,
        String(value),
      ]),
    },
    {
      title: "Breakpoints: var() is not allowed in a media query; these are for scripts",
      entries: Object.entries(breakpoints).map(([name, value]) => [
        `breakpoint-${name}`,
        px(value),
      ]),
    },
    {
      title: "Semantic colours",
      entries: Object.entries(semanticColor).map(([name, ref]) => [
        kebab(name),
        paletteVar(ref),
      ]),
    },
    {
      title: "Focus ring and target size",
      entries: [
        ["focus-ring-width", px(focusRing.width)],
        ["focus-ring-offset", px(focusRing.offset)],
        ["target", px(target)],
      ],
    },
    {
      title: "Motion, from packages/motion (springs have no CSS form)",
      entries: [
        ...Object.entries(motion.durations).map(([name, ms]): [string, string] => [
          `duration-${kebab(name)}`,
          `${ms}ms`,
        ]),
        ...Object.entries(motion.easings).map(([name, value]): [string, string] => [
          `easing-${kebab(name)}`,
          value,
        ]),
      ],
    },
  ];
}

export function renderCss(): string {
  const lines = [
    "/* Generated by packages/tokens/scripts/generate.ts from src/tokens.ts. Do not edit. */",
    "",
    ":root {",
  ];
  sections().forEach((section, index) => {
    if (index > 0) lines.push("");
    lines.push(`  /* ${section.title} */`);
    for (const [name, value] of section.entries)
      lines.push(`  ${PREFIX}${name}: ${value};`);
  });
  lines.push("}", "");
  return lines.join("\n");
}
